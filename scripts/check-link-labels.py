#!/usr/bin/env python3
"""Link-label host gate: `[label](url)` links whose label names a different host than the URL.

The #404 content-defect audit kept finding links like `[mof.gov.xx](https://other.example/...)`,
where a reader who trusts the label lands on a different site than the citation. Only labels that
are themselves a hostname or URL are checked; hosts match when equal or when one is a subdomain of
the other. Code spans and fenced code are skipped.

Mismatches already on main live in config/_link-label-baseline.json, so the gate fails only on
NEW ones (nothing turns it red without a commit behind it). Baseline entries that no longer occur
are reported as stale; rerun with --write-baseline to drop them.

Run: python3 scripts/check-link-labels.py [--write-baseline]
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "property-deep-dive"
BASELINE = ROOT / "config" / "_link-label-baseline.json"
BASELINE_COMMENT = (
    "Known link-label/href host mismatches, consumed by scripts/check-link-labels.py and regenerated by its "
    "--write-baseline flag. Each entry is a triage item for a verified fix: never change a URL or label "
    "without checking the live page. Hosts are normalised (lowercase, no www., port or path)."
)

_spec = importlib.util.spec_from_file_location(
    "check_citations", Path(__file__).parent / "check-citations.py"
)
_cc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_cc)
MD_LINK_RE, HOSTLIKE_LABEL_RE = _cc.MD_LINK_RE, _cc.HOSTLIKE_LABEL_RE

FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})(.*)")
TICKS_RE = re.compile(r"`+")
# `[robots.txt](...)` names a file, not a host; none of these is an IANA TLD (.md and .zip are).
FILE_EXTS = set(
    "aspx csv doc docx dwg dxf geojson gif htm html jpeg jpg json kml kmz odt ods pdf php png ppt "
    "pptx rtf shp svg txt xls xlsx xml".split()
)


def host(s: str) -> str:
    try:
        h = (urlparse(s if "://" in s else "//" + s).hostname or "").rstrip(".")
    except ValueError:
        return ""
    return h[4:] if h.startswith("www.") else h


def label_host(label: str) -> str:
    label = label.strip().strip("`*_")
    if not label or any(c.isspace() for c in label):
        return ""
    h = host(label)
    return (
        h if HOSTLIKE_LABEL_RE.match(h) and h.rsplit(".", 1)[1] not in FILE_EXTS else ""
    )


def same_site(a: str, b: str) -> bool:
    return a == b or a.endswith("." + b) or b.endswith("." + a)


def code_spans(line: str) -> list[tuple[int, int]]:
    # CommonMark: a run of N backticks closes at the next run of exactly N; unmatched runs are literal.
    runs = [m.span() for m in TICKS_RE.finditer(line)]
    spans, i = [], 0
    while i < len(runs):
        s, e = runs[i]
        j = next(
            (j for j in range(i + 1, len(runs)) if runs[j][1] - runs[j][0] == e - s),
            None,
        )
        if j is None:
            i += 1
        else:
            spans.append((s, runs[j][1]))
            i = j + 1
    return spans


def line_mismatches(line: str) -> list[tuple[str, str, str]]:
    """(raw label, label host, href host) for each mismatched link on one line."""
    spans, out, pos = code_spans(line), [], 0
    while m := MD_LINK_RE.search(line, pos):
        if any(s < m.start() < e for s, e in spans):
            pos = m.start() + 1
            continue
        pos = m.end()
        lh, uh = label_host(m["label"]), host(m["url"])
        if (
            lh
            and uh
            and not same_site(lh, uh)
            and lh != urlparse(m["url"]).path.rsplit("/", 1)[-1].lower()
        ):
            out.append((m["label"], lh, uh))
    return out


def text_mismatches(text: str) -> list[tuple[int, str, str, str]]:
    out, fence = [], None
    for n, line in enumerate(text.splitlines(), 1):
        f = FENCE_RE.match(line)
        if fence is None:
            # CommonMark: a backtick fence's info string may not contain a backtick.
            if f and (f[1][0] == "~" or "`" not in f[2]):
                fence = f[1]
            else:
                out += [(n, *mm) for mm in line_mismatches(line)]
        elif (
            f
            and f[1][0] == fence[0]
            and len(f[1]) >= len(fence)
            and not f[2].strip(" \t")
        ):
            fence = None
    return out


def scan() -> list[tuple[str, int, str, str, str]]:
    return [
        (p.relative_to(ROOT).as_posix(), *mm)
        for p in sorted(SKILL.rglob("*.md"))
        for mm in text_mismatches(p.read_text(encoding="utf-8"))
    ]


def compare(found: list[tuple], baseline: list[dict]) -> tuple[list[tuple], Counter]:
    """New findings (beyond the baseline count for their key) and stale baseline keys."""
    budget = Counter((b["file"], b["label"], b["href"]) for b in baseline)
    stale = budget - Counter((f, lh, uh) for f, _, _, lh, uh in found)
    new = []
    for f in found:
        key = (f[0], f[3], f[4])
        if budget[key]:
            budget[key] -= 1
        else:
            new.append(f)
    return new, stale


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Fail on link labels that name a different host than the URL."
    )
    ap.add_argument(
        "--write-baseline",
        action="store_true",
        help=f"rewrite {BASELINE.relative_to(ROOT)}",
    )
    args = ap.parse_args()

    found = scan()
    if args.write_baseline:
        rows = [{"file": f, "label": lh, "href": uh} for f, _, _, lh, uh in found]
        doc = {"_comment": BASELINE_COMMENT, "mismatches": rows}
        BASELINE.write_text(
            json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"wrote {len(rows)} baseline entries to {BASELINE.relative_to(ROOT)}")
        return 0

    new, stale = compare(
        found, json.loads(BASELINE.read_text(encoding="utf-8"))["mismatches"]
    )
    print(
        f"{len(found)} label/href host mismatch(es), {len(found) - len(new)} baselined"
    )
    for (f, lh, uh), k in sorted(stale.items()):
        print(
            f"::warning file={BASELINE.relative_to(ROOT)}::stale baseline entry x{k}: {f} {lh} -> {uh} "
            "(fixed? run --write-baseline)"
        )
    for f, n, label, _, uh in new:
        print(
            f"::error file={f},line={n}::link label [{label}] names a different host than its URL ({uh})"
        )
    return 1 if new else 0


if __name__ == "__main__":
    sys.exit(main())
